-- This is the generic **top-level** entity of the chFPGA data acquisition/channelizer/corner-turn/correlator firmware.
--
-- The code is configurable for multiple platforms (Virtex 6, Kintex 7, Ultrascale+) with optional GMII or SFP+ Ethernet interface, various clock sources, etc) through the generics.
-- A platform-specific wrapper file is used to define these generics for a specific platform and expose the useful ports.
entity chfpga is
	generic (
		PLATFORM_TYPE: platform_type_enum; -- identifies the type of platform on which the firmware is running. 0=Motherboard, 1=KC705
		PROTOCOL_VERSION: integer := 10;

		-- Clocking configuration

		SYSTEM_CLOCK_SOURCE: clk_source_enum := SYSCLK; -- "SYSCLK": the 200 MHz clock will be taken from sysclk_p/n (CC pins) or "SFP_REFCLK": the system clock is 125 MHz from the GTX reference clock
		SYSTEM_CLOCK_FREQ: real     := 250.0; -- System reference clock frequency, in MHz
		CT_CLK_SOURCE: ct_clk_source_enum := CORR_CLK;
		CHAN_CLK_SOURCE: chan_clk_source_enum := ADC; -- "ADC": Clock is taken directly from the ADC (single phase); "MMCM": 8-phase clock is generated by A MMCM fed by the ADC or the system clocks (the later allows for uninterrupted clocks)
		CHAN_CLK_FREQ: real         := 200.0; -- Channelizer clock frequency, in MHz. Used only if CHAN_CLK_SOURCE="MMCM".

		-- Buck sync

		BUCK_SYNC_ENABLE: boolean       := True; -- default state of the buck sync enable at startup
		BUCK_CLK_DIVIDE_FACTOR: integer := 12; -- Buck frequency is 200MHz/BUCK_CLK_DIVIDE_FACTOR/16

		-- BSB Monitor and control interface

		BSB_INTERFACE: bsb_interface_enum; -- UDP_GMII, UDP_SGMII or AXIS. Determines which ethernet interface to instantiate and connect to the BSB. If AXIS, the BSB control interface is connected directly to the top level ports *_axis_bsb_*.

		CAP_INTERFACE: cap_interface_enum := BSB; -- BSB or AXIS. Determines the destination of the capture bus. If BSB, capture is routed to bsb_master. If AXIS, capture buses are merged and sent to the external AXIS bus.

		-- ADC configuration

		-- Type of ADC to use.
		-- "EV8AQ160": Implements ADCDAQ data acquisiton logic for the EV8AQ160.
		-- "AXIS": Data provided over the axis_adc AXI4-Streaming interface
		ADC_TYPE: ADC_TYPE_ENUM := EV8AQ160;

		NUMBER_OF_ADCS: integer; -- Number of ADC data acquisition blocks (ADCDAQ) to be implemented. If 0, the channelizers ar fed directly from the adc_axis* bus.

		NUMBER_OF_ADC_BOARDS: integer    := 2; -- One SYNC and REFCLK for each FMC

		-- ADC_TO_ADC_BOARD_MAP maps each ADC to a specific ADC board. This is only used for the EV8AQ160 ADC type to associate an ADC with a mezzanine reference clock for clock waveform sampling. All boards must be specified somewhere in the list.
		ADC_TO_ADC_BOARD_MAP: integer_array(0 to NUMBER_OF_ADCS - 1) := divided_ramp(NUMBER_OF_ADCS, NUMBER_OF_ADCS/NUMBER_OF_ADC_BOARDS);

		-- EV8AQ160 ADC data acquisition logic configuration

		-- ADC_IS_DIFFERENTIAL indicates whether each ADC data and clock inputs are single-ended (FALSE) or differential (TRUE).

		ADC_IS_DIFFERENTIAL: bool_array_array := (0 to NUMBER_OF_ADCS - 1 => (0 to 8 => TRUE)); -- All inputs are differential by default unless specified otherwise by the top level

		-- ADC_INSTANTIATE_PLL determines which ADCDAQ need to instantiate a PLL to provide IOCLK and DIVCLK to ISERDES that are in non-adjacent banks, and to provide a BUFG-buffered global word clock.
		-- NOTE: A PLL (MMCM) could be used in theory for all data buses, but in practice we would run out of PLLs (there are only 2 per clock region).
		-- NOTE: On the Virtex 6, there is no fast clock routing for the outer IO pads to the PLL. So the use of a PLL is preferably limited to the center IO pads
		ADC_PROVIDE_BUFFERED_DIVCLK: bool_array( 0 to NUMBER_OF_ADCS - 1) := (1 => TRUE, others => FALSE); -- Indicates if this modules provides a buffered (BUFG) 200 MHz ADC clock (to be used to generate the processing clocks). Needs to be set only on those channels that will actually use it because we'll quickly run ot or BUFGs otherwise.

		ADC_INSTANTIATE_PLL: bool_array(0 to NUMBER_OF_ADCS - 1) := (others => FALSE); -- No PLL needed on this board, we all have direct or BUFMR connections to the deserializers.

		-- ADC_USE_EXT_DATA_CLK determines which ADC use the external (PLL-generated) IOCLK and DIVCLK. This is needed if the data bus lines end up in non-adjacent banks reachable by the IOBUF or BUFR.
		-- If FALSE, the clocks generated byIOCLK and BUFR will be used.
		-- NOTE: using a single PLL output for multiple ADC data buses is allowed, but that assumes that all data buses are relatively well in phase to be realigned with the IDELAY. This is reasonable assumption if all data buses come from the same ADC chip. It is not clear if this work well across multiple ADC chips.
		ADC_USE_EXT_DATA_CLK: bool_array(0 to NUMBER_OF_ADCS - 1) := (0 to 3 => TRUE, others => FALSE);

		ADC_CLOCKING_REGION_MAP: integer_array_array := (0 to NUMBER_OF_ADCS - 1 => (0 to 8 => 0)); -- Determines which clocking region each data and clock line uses

		CHAN_CLK_SOURCE_LANE: integer := 1; -- Indicate which ADC is the source of the channelizer clocks. Must be one that has PROVIDE_BUFFERED_DIVCLK=TRUE so we have a BUFG that can clock the logic across the chip


		-- F-Engine config
		FFT_TYPE: fft_type_enum;
		NUMBER_OF_CHANNELIZERS: INTEGER          := NUMBER_OF_ADCS; -- Number of channelizers to be implemented
		NUMBER_OF_CHANNELIZERS_WITH_FFT: integer := NUMBER_OF_CHANNELIZERS;
		CAPTURE_TYPE: chan_capture_type_enum; -- "PROBER": BRAM-based in-channelizer capture engine; "UCAP": URAM-based centralized UCAP capture engine.
		CAPTURE_BITS_PER_WORD: integer           := CHAN_CAPTURE_INFO(CAPTURE_TYPE).INPUT_WIDTH; -- number of bits in the words captured by capture engine

		-- Corner-turn engine config
		CT_TYPE: ct_type_enum;
		CT_LEVEL: integer := 1;

		CT_LANE_TO_LINK_MAP: integer_array   := (0 => -1, 1 => 0, 2 => 1, 3 => 2, 4 to 7 => -1); -- List indicating the GTX/GTY link number associated to each lane. -1 means a bypass  lane (no GTY, stays internal to the board).
		CT_LINK_TO_QUAD_MAP: integer_array   := (0 to 2 => 0); -- Indicates which quad is associated to each GTY link.
		CT_QUAD_TO_REFCLK_MAP: integer_array := (0 => 0); -- Indicates which refclk is associated with each QUAD
		CT_LANE_TO_GROUP_MAP: integer_array  := (0 to 7  => 0); -- Indicates to which lane group each logical lane is associated with

		BP_LINK_SPEED: integer                      := 0; -- 0=7.5 Gbps, 1-10Gbps.

		-- Correlator config

		CORR_TYPE: corr_type_enum                    := CORR44; -- "CORR44" or "UCORR44"
		CORR_READOUT_BINS: integer_array := (0=> 0);
		
		-- Data offload configuration

		DATA_LINK_TYPE: data_link_type_enum; -- NONE, XGE (10G), or UPACK_CGE (100G)
		DATA_LINK_LINK_TO_QUAD_MAP: integer_array := (0 => 0);
		DATA_LINK_QUAD_TO_REFCLK_MAP: integer_array  := (0 => 0);

		NUMBER_OF_DATA_LINKS: integer   := sel(DATA_LINK_TYPE /= NONE, DATA_LINK_LINK_TO_QUAD_MAP'LENGTH, 0); -- sel needed to prevent synth
		NUMBER_OF_DATA_LINK_REFCLKS: integer := sel(DATA_LINK_QUAD_TO_REFCLK_MAP'LENGTH > 0, max(DATA_LINK_QUAD_TO_REFCLK_MAP)+1, 0); -- sel needed to prevent synthesizer crash

		-- Peripheral configuration

		BLINKER_PRESENT: boolean         := TRUE; -- Indicates if the LED flasher is to be implemented by setting the DUMMY flag of the BLINKER module
		NUMBER_OF_I2C_PORTS: integer     := 1;
		NUMBER_OF_SPI_PORTS: integer     := 1;
		IMPLEMENT_LCD: boolean           := FALSE;
		IMPLEMENT_SWITCHER_SYNC: boolean := TRUE;
		IMPLEMENT_FAN: boolean           := TRUE;
		IMPLEMENT_ARM_SPI: boolean       := TRUE;

		-- Computed CT Engine parameters
		NUMBER_OF_CT_LINKS: integer      := CT_LINK_TO_QUAD_MAP'LENGTH; -- Number of GTXes for both the backplane PCB and QSFP shuffle links. Usually matches the number of 1st crossbar output lanes.
		NUMBER_OF_CT_REFCLKS: integer    := sel(CT_QUAD_TO_REFCLK_MAP'LENGTH > 0, max(CT_QUAD_TO_REFCLK_MAP) + 1, 0); -- sel needed to prevent synthesizer crash

--			NUMBER_OF_CT_LINKS: integer          := CT_LINK_TO_QUAD_MAP'LENGTH; -- Number of GTXes for both the backplane PCB and QSFP shuffle links. Usually matches the number of 1st crossbar output lanes.
--			NUMBER_OF_CT_REFCLKS: integer        := max(CT_QUAD_TO_REFCLK_MAP)+1;

		SIM: boolean := FALSE -- Indicates this is running as a simulation. Used to accelerate simulations
	);
	port (
		------------------------------------
		-- SYSTEM
		------------------------------------

		-- Reset line

		cpu_reset: in std_logic; -- Hardware reset generated by the Motherboard

		-- Motherboard Buttons and LEDs

		GPIO_BUTTON0: in  std_logic := '0'; -- Button on the Motherboard
		gpio_led: out  std_logic_vector(7 downto 0); -- Row of 8 leds on the Motherboard
		GPIO_DIP_SW: in std_logic_vector(3 downto 0) := (others => '0'); -- 4 DIP switches used to set the IP address of the board

		-- Motherboard LCD

		LCD_DB: out  std_logic_vector(7 downto 4); -- Motherboard LCD display data bus (4 bits wide)
		LCD_E: out  std_logic; -- Motherboard LCD display Enable line
		LCD_RS: out  std_logic; -- Motherboard LCD display RS line
		LCD_RW: out  std_logic; -- Motherboard LCD Read/Write line

		-- Motherboard Fan

		FAN_PWM: out  std_logic; -- Controls he transistors that turns on the FPGA fan. Can be used to modulate the fan speed.
		FAN_TACH: in  std_logic := '0'; -- Readout of the FPGA fan tachymeter. Provides 2 pulses per turn, but the pulses are noisy.

		-- Motherboard Current and voltage monitors

		VAUX_CURR_N: in  std_logic := '0';
		VAUX_CURR_P: in  std_logic := '0'; -- Analog input to the internal FPGA System Monitor ADC. Measures the board current on the 12V supply through a current sensor.
		VAUX_VOLT_N: in  std_logic := '0';
		VAUX_VOLT_P: in  std_logic := '0';  -- Analog input to the internal FPGA System Monitor ADC. Measures 12V supply voltage through a voltage divider.
		VP: in  std_logic := '0';
		VN: in  std_logic := '0';

		-- Clock inputs

		clk10: in std_logic; -- BUFG-Buffered 10 MHz board reference clock with well known phase relative to the ADC clocks and  all other boards. Used to synchronize ADC startup. Typically synchronous to the IRIGB timestamp signal, but not necessary.
		clk10_sel: out std_logic; -- Reference clock selection signal
		sysclk_p: in std_logic := '0'; -- 200 MHz unbuffered differential clock. Used as a master clock if  SYSTEM_CLOCK_SOURCE = "SYSCLK";
		sysclk_n: in std_logic := '1';
		sysclk_bufg: in std_logic := '0'; -- BUFG-buffered 200 MHz used as a master clock if  SYSTEM_CLOCK_SOURCE = "SYSCLK_BUFG";
		sfp_clk_p: in std_logic := '0'; -- 125 MHz SFP reference clock, generated on-board using a high quality oscillator. Used as a master clock if  SYSTEM_CLOCK_SOURCE = "SFP_REFCLK"; Also used to synchronize the MGT used to communicate to the SFP.
		sfp_clk_n: in std_logic := '1';

		-- External PLL

		pll_oscout: in std_logic := '0'; -- BUFG-buffered External PLL VCXO clock
		pll_sync: out std_logic; -- PLL sync signal approximately synchronous to pll_oscout. Will be retimed on the falling edge and then then the rising edge of pll_oscout.
		-- Clock monitoring inputs

		raw_clk10: in std_logic := '0'; -- Buffered 10 MHz reference. Used for upstream clock frequency measurement only.
		mgt_clk100: in std_logic := '0'; -- Buffered MGT 100 MHz reference clock. Used by Frequency counter to debug connectivity
		mgt_clk200: in std_logic := '0'; -- Buffered MGT 200 MHz reference clock. Used by Frequency counter to debug connectivity
		mgt_clk125: in std_logic := '0'; -- Buffered MGT 125 MHz reference clock. Used by Frequency counter to debug connectivity

		-- On-board processor serial interface (used to access configuration registers prior to networking setup)
		arm_spi_sck: in std_logic := '0';
		arm_spi_miso: out std_logic;
		arm_spi_mosi: in std_logic := '0';
		arm_spi_cs_n: in std_logic := '0';

		arm_irq_in: in std_logic := '0'; -- Used for hardware validation only
		arm_irq_out: out std_logic; -- Used for hardware validation only
		arm_irq_oe: out std_logic; -- Used for hardware validation only

		flash_cs_in: in std_logic := '0';
		flash_cs_out: out std_logic;
		flash_cs_oe: out std_logic;  -- Active-high: enables GPIO reset output driver.

		gpio_rst_in: in std_logic := '0';
		gpio_rst_out: out std_logic;
		gpio_rst_oe: out std_logic;  -- Active-high: enables GPIO reset output driver.

		gpio_irq_in: in std_logic := '0';
		gpio_irq_out: out std_logic;
		gpio_irq_oe: out std_logic;  -- Active-high: enables GPIO reset output driver.

		uart_rx_in: in std_logic := '0';
		uart_rx_out: out std_logic;
		uart_rx_oe: out std_logic;

		uart_tx_in: in std_logic := '0';
		uart_tx_out: out std_logic;
		uart_tx_oe: out std_logic;


		-- Backplane signals

		-- time_trig(0): backplane IRIG-B time, time_trig(1): backplane trigger
		time_trig: in std_logic_vector(0 to 1) := (others => '0');
		bp_buck_sync: inout std_logic;

		bp_gpio_int_in: in std_logic := '0';
		bp_gpio_int_out: out std_logic;
		bp_gpio_int_oe: out std_logic;


		-- User outputs

		user_mux_out: out std_logic_vector(0 to 3);
		user_mux_in: in std_logic_vector(0 to 3) := (others => '0');
		user_mux_oe: out std_logic_vector(0 to 3);

		-- Motherboard SMA clocks

		clk10_out: out  std_logic; -- Delayed 10 MHz FMC Reference clock monitor. The delay line is used to align the ADC SYNC signal with the ADC clock.

		------------------------------------
		-- Motherboard GMII PHY Gigabit Ethernet Interface (Marvell Alaska 10-100-1000BASE-T PHY)
		------------------------------------
		phy_rxclk: in  std_logic := '0'; -- Receive byte clock recovered  by the PHY chip
		phy_txer: out std_logic; -- Enabled to transmit an error condition to the PHY
		phy_reset_l: out std_logic; -- Active LOW PHY reset
		phy_rxctrl_rxdv: in  std_logic := '0'; -- RX Data Valid flag from the PHY
		phy_rxd: in  std_logic_vector(7 downto 0) := (others => '0'); -- RX Data from the PHY

		phy_txc_gtxclk: out std_logic; -- 125 MHz clock provided to the PHY to clock the Tx bus
		phy_txctl_txen: out std_logic; -- Indicates that valid data is presented on the PHY TX bus.
		phy_txd: out  std_logic_vector(7 downto 0); -- Tx Data bus to the PHY
		phy_txclk: in std_logic := '0'; -- 125 MHz TX clock supplied *by* the PHY. This is not used as we generate our own clock internally.

		-- ------------------------------------
		-- -- Motherboard PMBus
		-- ------------------------------------
		-- PMBUS_SCK: inout std_logic; -- Motherboard PMBus (I2C) clock (bidirectional)
		-- PMBUS_SDA: inout std_logic; -- Motherboard PMBus (I2C) data (bidirectional)

		------------------------------------
		-- Motherboard SFP (Gbit Ethernet)
		------------------------------------
		-- SFP signals to be conencted to pins according to the UCF
		-- SFP_LOS: in std_logic; -- SFP Loss of Signal flag
		sfp_tx_p: out std_logic; -- Serialized data from the FPGA MGT to the SFP
		sfp_tx_n: out std_logic;
		sfp_rx_p: in std_logic := '0'; -- Serialized data from the SFP to the FPGA MGT
		sfp_rx_n: in std_logic := '1';

		-- Status signals

		sfp_status_vector: out std_logic_vector(15 downto 0); -- Core status.
		sfp_mmcm_locked: out std_logic;
		sfp_reset_done: out std_logic;
		tx_ready: out std_logic;

		------------------------------------
		-- 10G Ethernet Interfaces
		------------------------------------

		xge_tx_p: out std_logic_vector(0 to NUMBER_OF_DATA_LINKS - 1);
		xge_tx_n: out std_logic_vector(0 to NUMBER_OF_DATA_LINKS - 1);
		xge_rx_p: in std_logic_vector(0 to NUMBER_OF_DATA_LINKS - 1) := (others => '0');
		xge_rx_n: in std_logic_vector(0 to NUMBER_OF_DATA_LINKS - 1) := (others => '1');
		-- Gigabit transceiver refrenece clocks (typically 156.25 MHz)

		xge_refclk_p: in std_logic_vector(0 to NUMBER_OF_DATA_LINK_REFCLKS - 1) := (others => '0');
		xge_refclk_n: in std_logic_vector(0 to NUMBER_OF_DATA_LINK_REFCLKS - 1) := (others => '1');

		------------------------------------
		-- 100G Ethernet Interfaces
		------------------------------------

		cge_tx_p: out std_logic_vector(0 to 3); -- don't specify a default value, otherwise it will force inferring a OBUF and will prevent the port from being removed if the port is not used in some configs
		cge_tx_n: out std_logic_vector(0 to 3);

		-- Gigabit transceiver refrenece clocks (typically 156.25 MHz)

		cge_refclk_p: in std_logic := '0';
		cge_refclk_n: in std_logic := '1';

		------------------------------------
		-- Corner-Turn Engine
		------------------------------------
		-- Gigabit Transceiver links to the backplane for intra-crate and inter-crate data transfers
		bp_shuffle_tx_p: out std_logic_vector(0 to NUMBER_OF_CT_LINKS - 1);
		bp_shuffle_tx_n: out std_logic_vector(0 to NUMBER_OF_CT_LINKS - 1);
		bp_shuffle_rx_p: in std_logic_vector(0 to NUMBER_OF_CT_LINKS - 1) := (others => '0');
		bp_shuffle_rx_n: in std_logic_vector(0 to NUMBER_OF_CT_LINKS - 1) := (others => '1');
		-- Gigabit transceiver refrenece clocks (typically 156.25 MHz)

		bp_shuffle_refclk_p: in std_logic_vector(0 to NUMBER_OF_CT_REFCLKS - 1) := (others => '0');
		bp_shuffle_refclk_n: in std_logic_vector(0 to NUMBER_OF_CT_REFCLKS - 1) := (others => '1');

		------------------------------------
		-- AXI-Streaming ADC interface
		------------------------------------
		-- Data bus contains 8x 16-bit words.
		-- Samples are MSB-aligned in the word.
		-- First word in the group is in bits 15:0
		-- AXIS Clock is sampling_frequency / 8

		adc_axis_tdata: in slv128_array(0 to NUMBER_OF_ADCS - 1) := (others => (others => '0'));
		adc_axis_tvalid: in std_logic_vector(0 to NUMBER_OF_ADCS - 1) := (others => '0');
		adc_axis_clk: in std_logic_vector(0 to NUMBER_OF_ADCS - 1) := (others => '0');
		-- Clock output of the ADC tiles (for monitoring)

		adc_clkout: in std_logic_vector(0 to NUMBER_OF_ADCS - 1) := (others => '0'); -- ADC tile clock output (for monitoring)
		adc_sysref: in std_logic := '0'; -- PL_SYSREF, reclocked through adc_axis_clk (plclk)

		-- ADC low-level control and status signals (overflow, calibration, etc.)

		adc_clear_or: out std_logic_vector(0 to NUMBER_OF_ADCS - 1) := (others => '0');
		adc_clear_ov: out std_logic_vector(0 to NUMBER_OF_ADCS - 1) := (others => '0');
		adc_cm_ov: in std_logic_vector(0 to NUMBER_OF_ADCS - 1) := (others => '0');
		adc_cm_uv: in std_logic_vector(0 to NUMBER_OF_ADCS - 1) := (others => '0');
		adc_or: in std_logic_vector(0 to NUMBER_OF_ADCS - 1) := (others => '0');
		adc_ot1: in std_logic_vector(0 to NUMBER_OF_ADCS - 1) := (others => '0');
		adc_ot2: in std_logic_vector(0 to NUMBER_OF_ADCS - 1) := (others => '0');
		adc_ov: in std_logic_vector(0 to NUMBER_OF_ADCS - 1) := (others => '0');
		adc_cal_frozen: in std_logic_vector(0 to NUMBER_OF_ADCS - 1) := (others => '0');
		adc_cal_freeze: out std_logic_vector(0 to NUMBER_OF_ADCS - 1) := (others => '0');
		adc_cal_signal_detect: in std_logic_vector(0 to NUMBER_OF_ADCS - 1) := (others => '0');

		------------------------------------
		-- FMC ADC interface
		------------------------------------

		adc_data_p: in SLV8_ARRAY(0 to NUMBER_OF_ADCS - 1) := (others => (others => '0'));
		adc_data_n: in SLV8_ARRAY(0 to NUMBER_OF_ADCS - 1) := (others => (others => '1'));
		adc_clk_p: in std_logic_vector(0 to NUMBER_OF_ADCS - 1) := (others => '0');
		adc_clk_n: in std_logic_vector(0 to NUMBER_OF_ADCS - 1) := (others => '1');


		-- ADC RESET and SYNC signals

		ADC_SYNC_P: out std_logic_vector(0 to NUMBER_OF_ADC_BOARDS - 1); -- SYNC signal to the ADC (or the recynchronization circuit that drives the ADC SYNC)
		ADC_SYNC_N: out std_logic_vector(0 to NUMBER_OF_ADC_BOARDS - 1);
		ADC_RST_N: out std_logic_vector(0 to NUMBER_OF_ADC_BOARDS - 1); -- Active LOW ADC reset line, common to both ADC chips.

		-- SPI signals

		spi_sck: out std_logic; -- SPI clock to the FMC. Typically 1 MHz.
		spi_miso: in std_logic_vector(0 to NUMBER_OF_SPI_PORTS - 1) := (others => '0'); -- SPI data from the FMC
		spi_mosi: out std_logic; -- SPI data to the FMC
