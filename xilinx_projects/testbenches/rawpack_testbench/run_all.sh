BLOCKS_PER_PACKET=90
BLOCKS_PER_PACKET=90 STREAM_ENABLE=1
BLOCKS_PER_PACKET=90 GAP_PERIOD=2 SOURCE=1 CHAN_A=7 CHAN_B=0
BLOCKS_PER_PACKET=4 NUMBER_OF_PACKETS=300
BLOCKS_PER_PACKET=5 GAP_PERIOD=9 NUMBER_OF_PACKETS=200
BLOCKS_PER_PACKET=1 NUMBER_OF_PACKETS=200
CHANGE_TEST=1
CHANGE_TEST=1 RESET_TEST=1 BLOCKS_PER_PACKET=20
